def build_bank() -> dict[str, list[dict]]:
    bank: dict[str, list[dict]] = {}
    for module, concepts in CONCEPTS.items():
        questions = []
        for index, (term, definition, native_difficulty) in enumerate(concepts):
            definition_distractors = [concepts[(index + step) % len(concepts)][1] for step in (3, 7, 11)]
            term_distractors = [concepts[(index + step) % len(concepts)][0] for step in (3, 7, 11)]
            variants = {
                "beginner": (f"Which description best matches {term}?", definition, definition_distractors),
                "intermediate": (f"Which networking term matches this description: {definition}", term, term_distractors),
                "advanced": (f"A network engineer observes this behavior: {definition} Which concept is being applied?", term, term_distractors),
            }
            for difficulty, (q, correct, distractors) in variants.items():
                questions.append({
                    "id": f"{module}-{difficulty[0]}-{index + 1:02d}", "module": module,
                    "difficulty": difficulty, "native_difficulty": native_difficulty,
                    "q": q, "correct": correct, "options": [correct, *distractors],
                    "explanation": f"{term}: {definition}", "topic": MODULES[module]["title"],
                })
        bank[module] = questions
    return bank


QUESTION_BANK = build_bank()
